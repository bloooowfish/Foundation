use std::{collections::HashMap, path::PathBuf};

use serde_yaml_ng::Value;

fn format_value(value: &Value) -> String {
    match value {
        Value::Number(number) => number.as_u64().unwrap_or_default().to_string(),
        Value::String(string) => format!("\"{string}\""),
        Value::Sequence(values) => {
            let mut values_str = Vec::new();
            for value in values {
                values_str.push(format_value(value));
            }

            format!("[{}]", values_str.join(", "))
        }
        _ => unimplemented!(),
    }
}

fn domain_expr_for_key(key: &str) -> &'static str {
    match key {
        "ServerZoneIpcType" => "crate::protocol_profile::OpcodeDomain::ServerZone",
        "ClientZoneIpcType" => "crate::protocol_profile::OpcodeDomain::ClientZone",
        "ServerLobbyIpcType" => "crate::protocol_profile::OpcodeDomain::ServerLobby",
        "ClientLobbyIpcType" => "crate::protocol_profile::OpcodeDomain::ClientLobby",
        "ServerChatIpcType" => "crate::protocol_profile::OpcodeDomain::ServerChat",
        "ClientChatIpcType" => "crate::protocol_profile::OpcodeDomain::ClientChat",
        "CustomIpcType" => "crate::protocol_profile::OpcodeDomain::Custom",
        other => panic!("Unsupported opcode domain in YAML: {other}"),
    }
}

fn main() {
    // Add link search directory for Oodle
    println!(
        "cargo:rustc-link-search={}/../oodle",
        env!("CARGO_MANIFEST_DIR")
    );

    // Generate IPC opcodes
    {
        let mut d = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
        d.push("../resources/data/opcodes.yml");
        let mut overlay_path = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
        overlay_path.push("../resources/data/opcodes.housing.yml");

        println!("cargo::rerun-if-changed={}", d.to_str().unwrap());
        println!("cargo::rerun-if-changed={}", overlay_path.to_str().unwrap());

        let mut output_str =
            "//!This file is automatically generated from `resources/data/opcodes.yml` + `resources/data/opcodes.housing.yml`! Do not edit this manually or commit to the repository.\nuse std::io::{Read, Seek, Write};\nuse binrw::{BinRead, BinResult, BinWrite, Endian};\nuse crate::packet::PredefinedOpcode;\n".to_string();

        let opcodes_buffer = std::fs::read_to_string(d).unwrap();
        let mut json: Value = serde_yaml_ng::from_str(&opcodes_buffer).unwrap();

        if overlay_path.exists() {
            let overlay_buffer = std::fs::read_to_string(&overlay_path).unwrap();
            let overlay_val: Value = serde_yaml_ng::from_str(&overlay_buffer).unwrap();
            let base_map = json.as_mapping_mut().unwrap();
            if let Some(overlay_map) = overlay_val.as_mapping() {
                for (section_key, section_val) in overlay_map {
                    let Some(overlay_seq) = section_val.as_sequence() else {
                        continue;
                    };
                    let base_entry = base_map
                        .entry(section_key.clone())
                        .or_insert_with(|| Value::Sequence(Vec::new()));
                    let base_seq = base_entry.as_sequence_mut().unwrap();

                    for item in overlay_seq {
                        let item_name = item
                            .as_mapping()
                            .and_then(|m| m.get("name"))
                            .and_then(|n| n.as_str())
                            .expect("Overlay opcode entry missing string `name`");
                        if let Some(existing) = base_seq.iter_mut().find(|existing| {
                            existing
                                .as_mapping()
                                .and_then(|m| m.get("name"))
                                .and_then(|n| n.as_str())
                                == Some(item_name)
                        }) {
                            *existing = item.clone();
                        } else {
                            base_seq.push(item.clone());
                        }
                    }
                }
            }
        }

        for element in json.as_mapping().unwrap() {
            let key = element.0.as_str().unwrap_or_default();
            let domain_expr = domain_expr_for_key(key);
            let opcodes = element.1.as_sequence().unwrap();
            let mut seen_opcodes = Vec::new();

            let mut output_md = String::new();

            output_md.push_str("| Opcode | Size (in bytes) | Name | Comment |\n");
            output_md.push_str("| --- | --- | --- | --- |\n");

            // beginning
            output_str.push_str("#[derive(Copy, Clone, PartialEq, Eq, Debug)]\n");
            output_str.push_str(&format!("pub enum {key} {{\n"));

            for opcode in opcodes {
                let opcode = opcode.as_mapping().unwrap();
                let size = opcode.get("size").unwrap().as_u64().unwrap();
                let name = opcode.get("name").unwrap().as_str().unwrap();
                let comment = if let Some(comment) = opcode.get("comment") {
                    let comment = comment.as_str().unwrap_or_default();
                    output_str.push_str(&format!("/// {comment}\n"));

                    comment
                } else {
                    ""
                };

                let opcode = opcode.get("opcode").unwrap().as_u64().unwrap();

                if !seen_opcodes.contains(&opcode) {
                    seen_opcodes.push(opcode);
                } else {
                    panic!(
                        "{key}.{name} has the same opcode ({opcode}) as another, this isn't possible!"
                    );
                }

                output_str.push_str(&format!("{name},\n"));

                // NOTE: This makes the assumption that the Data type is just the key but with Data at the end!
                let data_type_name = key.replace("Type", "Data");

                let module = if key.contains("Chat") {
                    "chat::"
                } else if key.contains("Zone") {
                    "zone::"
                } else if key.contains("Lobby") {
                    "lobby::"
                } else {
                    "" // For the custom IPC I guess?
                };

                output_md.push_str(&format!("| {opcode} (0x{opcode:X}) | {size} | [{name}](self::{module}{data_type_name}::{name}) | {comment} |\n"));
            }

            output_str.push_str("Unknown(u16),\n");

            // end
            output_str.push_str("}\n\n");

            output_str.push_str(&format!("impl Default for {key} {{\n"));
            output_str.push_str("fn default () -> Self {\n");
            output_str.push_str("Self::Unknown(0)\n");
            output_str.push_str("}\n");
            output_str.push_str("}\n");

            output_str.push_str(&format!("impl {key} {{\n"));
            output_str.push_str("pub const ALL_NAMED: &'static [(&'static str, u16, u32)] = &[\n");
            for opcode in opcodes {
                let opcode = opcode.as_mapping().unwrap();
                let name = opcode.get("name").unwrap().as_str().unwrap();
                let size = opcode.get("size").unwrap().as_u64().unwrap();
                let opc = opcode.get("opcode").unwrap().as_u64().unwrap();
                output_str.push_str(&format!("(\"{name}\", {opc}, {size}),\n"));
            }
            output_str.push_str("];\n\n");

            output_str.push_str(&format!(
                "pub const fn domain() -> crate::protocol_profile::OpcodeDomain {{\n    {domain_expr}\n}}\n\n"
            ));

            output_str
                .push_str("pub const fn variant_index(&self) -> Option<usize> {\nmatch self {\n");
            for (idx, opcode) in opcodes.iter().enumerate() {
                let name = opcode
                    .as_mapping()
                    .unwrap()
                    .get("name")
                    .unwrap()
                    .as_str()
                    .unwrap();
                output_str.push_str(&format!("{key}::{name} => Some({idx}),\n"));
            }
            output_str.push_str(&format!("{key}::Unknown(_) => None,\n}}\n}}\n\n"));

            output_str.push_str("pub fn from_variant_index(idx: usize) -> Self {\nmatch idx {\n");
            for (idx, opcode) in opcodes.iter().enumerate() {
                let name = opcode
                    .as_mapping()
                    .unwrap()
                    .get("name")
                    .unwrap()
                    .as_str()
                    .unwrap();
                output_str.push_str(&format!("{idx} => {key}::{name},\n"));
            }
            output_str.push_str("_ => unreachable!(),\n}\n}\n\n");

            output_str.push_str("pub fn from_wire_opcode(raw: u16) -> Self {\n");
            output_str
                .push_str("    crate::protocol_profile::resolve_wire_index(Self::domain(), raw)\n");
            output_str.push_str("        .map(Self::from_variant_index)\n");
            output_str.push_str("        .unwrap_or(Self::Unknown(raw))\n");
            output_str.push_str("}\n\n");

            output_str.push_str("pub const fn default_opcode(&self) -> u16 {\nmatch self {\n");
            for opcode in opcodes {
                let opcode = opcode.as_mapping().unwrap();
                let name = opcode.get("name").unwrap().as_str().unwrap();
                let opc = opcode.get("opcode").unwrap().as_u64().unwrap();
                output_str.push_str(&format!("{key}::{name} => {opc},\n"));
            }
            output_str.push_str(&format!("{key}::Unknown(opcode) => *opcode,\n}}\n}}\n\n"));

            output_str.push_str("pub const fn default_size(&self) -> u32 {\nmatch self {\n");
            for opcode in opcodes {
                let opcode = opcode.as_mapping().unwrap();
                let name = opcode.get("name").unwrap().as_str().unwrap();
                let size = opcode.get("size").unwrap().as_u64().unwrap();
                output_str.push_str(&format!("{key}::{name} => {size},\n"));
            }
            output_str.push_str(&format!("{key}::Unknown(_) => 0,\n}}\n}}\n\n"));

            // Used for runtime opcode resolution across all IPC packets
            output_str.push_str("/// Returns the active runtime integer opcode.\n");
            output_str.push_str("pub(crate) fn get_opcode(&self) -> u16 {\n");
            output_str.push_str("if let Some(idx) = self.variant_index() {\n");
            output_str.push_str(
                "    crate::protocol_profile::resolve_opcode_by_index(Self::domain(), idx)\n",
            );
            output_str.push_str("} else if let Self::Unknown(opcode) = self {\n");
            output_str.push_str("    *opcode\n");
            output_str.push_str("} else {\n");
            output_str.push_str("    unreachable!()\n");
            output_str.push_str("}\n");
            output_str.push_str("}\n\n");
            output_str.push_str("}\n\n");

            output_str.push_str(&format!("impl BinRead for {key} {{\n"));
            output_str.push_str("    type Args<'a> = ();\n");
            output_str.push_str("    fn read_options<R: Read + Seek>(reader: &mut R, endian: Endian, args: Self::Args<'_>) -> BinResult<Self> {\n");
            output_str.push_str("        let raw = u16::read_options(reader, endian, args)?;\n");
            output_str.push_str("        Ok(Self::from_wire_opcode(raw))\n");
            output_str.push_str("    }\n");
            output_str.push_str("}\n\n");

            output_str.push_str(&format!("impl BinWrite for {key} {{\n"));
            output_str.push_str("    type Args<'a> = ();\n");
            output_str.push_str("    fn write_options<W: Write + Seek>(&self, writer: &mut W, endian: Endian, args: Self::Args<'_>) -> BinResult<()> {\n");
            output_str.push_str("        self.get_opcode().write_options(writer, endian, args)\n");
            output_str.push_str("    }\n");
            output_str.push_str("}\n\n");

            output_str.push_str(&format!("impl PredefinedOpcode for {key} {{\n"));

            // sizes
            output_str.push_str("fn calc_size(&self) -> u32 {\n");
            output_str.push_str("if let Some(idx) = self.variant_index() {\n");
            output_str.push_str(
                "    crate::protocol_profile::resolve_size_by_index(Self::domain(), idx)\n",
            );
            output_str.push_str("} else {\n");
            output_str.push_str("    unreachable!()\n");
            output_str.push_str("}\n");
            output_str.push_str("}\n\n");

            // names
            output_str.push_str("fn get_name(&self) -> &'static str {\n");
            output_str.push_str("match self {\n");

            for opcode in opcodes {
                let opcode = opcode.as_mapping().unwrap();
                let name = opcode.get("name").unwrap().as_str().unwrap();

                output_str.push_str(&format!("{key}::{name} => \"{name}\",\n"));
            }

            output_str.push_str(&format!("{key}::Unknown(_) => \"Unknown\",\n"));

            output_str.push_str("}\n\n");
            output_str.push_str("}\n\n");

            // opcodes
            output_str.push_str("/// Returns the active runtime integer opcode.\n");
            output_str.push_str("fn get_opcode(&self) -> u16 {\n");
            output_str.push_str("self.get_opcode()\n");
            output_str.push_str("}\n\n");

            // comments
            output_str.push_str("fn get_comment(&self) -> Option<&'static str> {\n");
            output_str.push_str("match self {\n");

            for opcode in opcodes {
                let opcode = opcode.as_mapping().unwrap();
                let name = opcode.get("name").unwrap().as_str().unwrap();

                if let Some(comment) = opcode.get("comment") {
                    let comment = comment.as_str().unwrap_or_default();
                    output_str.push_str(&format!("{key}::{name} => Some(\"{comment}\"),\n"));
                }
            }

            output_str.push_str("_ => None,\n");

            output_str.push_str("}\n\n");
            output_str.push_str("}\n\n");

            // end impl
            output_str.push_str("}\n\n");

            std::fs::write(format!("src/doc_{}.md", key.to_lowercase()), output_md)
                .expect("Failed to write opcodes file!");
        }

        std::fs::write("src/opcodes.rs", output_str).expect("Failed to write opcodes file!");
    }

    // Generate constants
    {
        let mut d = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
        d.push("../resources/data/constants.yml");

        println!("cargo::rerun-if-changed={}", d.to_str().unwrap());

        let mut type_map: HashMap<&str, &str> = HashMap::new();
        type_map.insert("LOBBY_GAME_VERSION", "u32");
        type_map.insert("OBFUSCATION_ENABLED_MODE", "u8");
        type_map.insert("OBFUSCATION_TABLE_RADIXES", "[i32; 3]");
        type_map.insert("OBFUSCATION_TABLE_MAX", "[i32; 3]");
        type_map.insert("SUPPORTED_BOOT_VERSION", "&str");
        type_map.insert("SUPPORTED_GAME_VERSION", "&str");
        type_map.insert("LEVEL_MAIN", "[u32; 100]");

        let mut output_str =
            "//! This file is automatically generated from `resources/data/constants.yml`! Do not edit it manually or commit to the repository.\n"
                .to_string();

        let constants_buffer = std::fs::read_to_string(d).unwrap();
        let yml: Value = serde_yaml_ng::from_str(&constants_buffer).unwrap();
        for (key, value) in yml.as_mapping().unwrap() {
            let mut value_type = type_map
                .get(key.clone().as_str().unwrap())
                .unwrap_or(&"usize")
                .to_string();

            // This is special because it also defines how many expansions we support.
            if key == "SUPPORTED_EXPAC_VERSIONS" {
                let max_expansions = value.as_sequence().unwrap().len();
                output_str.push_str(&format!(
                    "pub const MAX_EXPANSION: usize = {max_expansions};\n"
                ));
                value_type = format!("[&str; {max_expansions}]");
            }

            let value_display = format_value(value);

            output_str.push_str(&format!(
                "pub const {}: {value_type} = {};\n",
                key.as_str().unwrap(),
                value_display
            ));
        }

        std::fs::write("src/constants.rs", output_str).expect("Failed to write constants file!");
    }

    // Generate festivals
    {
        let mut d = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
        d.push("../resources/data/festivals.yml");

        println!("cargo::rerun-if-changed={}", d.to_str().unwrap());

        let mut output_str =
            "//! This file is automatically generated from `resources/data/festivals.yml`! Do not edit it manually or commit to the repository.\n"
                .to_string();

        output_str.push_str("pub fn festival_name(id: u16) -> Option<&'static str> {\n");
        output_str.push_str("match id {\n");

        let festivals_buffer = std::fs::read_to_string(d).unwrap();
        let yml: Value = serde_yaml_ng::from_str(&festivals_buffer).unwrap();
        for value in yml.as_sequence().unwrap() {
            output_str.push_str(&format!(
                "{} => Some(\"{}\"),\n",
                value.get("Id").unwrap().as_i64().unwrap(),
                value.get("Name").unwrap().as_str().unwrap()
            ));
        }

        output_str.push_str("_ => None,\n");
        output_str.push_str("}\n");
        output_str.push_str("}\n");

        output_str.push_str("pub fn festival_list() -> &'static [(u16, &'static str)] {\n");
        output_str.push_str("&[\n");
        for value in yml.as_sequence().unwrap() {
            output_str.push_str(&format!(
                "({}, \"{}\"),\n",
                value.get("Id").unwrap().as_i64().unwrap(),
                value.get("Name").unwrap().as_str().unwrap()
            ));
        }
        output_str.push_str("]\n");
        output_str.push_str("}\n");

        std::fs::write("src/festivals.rs", output_str).expect("Failed to write constants file!");
    }
}
