use std::path::PathBuf;

use serde_yaml_ng::Value;

pub const OPCODES_HEADER: &str = "//!This file is automatically generated from `resources/data/opcodes.yml` + `resources/data/opcodes.housing.yml`! Do not edit this manually or commit to the repository.\nuse std::io::{Read, Seek, Write};\nuse binrw::{BinRead, BinResult, BinWrite, Endian};\nuse crate::packet::PredefinedOpcode;\n";

fn domain_expr_for_key(key: &str) -> &'static str {
    match key {
        "ServerZoneIpcType" => "crate::protocol_profile::OpcodeDomain::ServerZone",
        "ClientZoneIpcType" => "crate::protocol_profile::OpcodeDomain::ClientZone",
        "ServerLobbyIpcType" => "crate::protocol_profile::OpcodeDomain::ServerLobby",
        "ClientLobbyIpcType" => "crate::protocol_profile::OpcodeDomain::ClientLobby",
        "ServerChatIpcType" => "crate::protocol_profile::OpcodeDomain::ServerChat",
        "ClientChatIpcType" => "crate::protocol_profile::OpcodeDomain::ClientChat",
        "CustomIpcType" => "crate::protocol_profile::OpcodeDomain::Custom",
        other => panic!("Unsupported opcode domain in YAML: {other}"),
    }
}

pub fn merge_housing_overlay(json: &mut Value) {
    let mut overlay_path = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    overlay_path.push("../resources/data/opcodes.housing.yml");

    println!("cargo::rerun-if-changed={}", overlay_path.to_str().unwrap());

    if !overlay_path.exists() {
        return;
    }

    let overlay_buffer = std::fs::read_to_string(&overlay_path).unwrap();
    let overlay_val: Value = serde_yaml_ng::from_str(&overlay_buffer).unwrap();
    let base_map = json.as_mapping_mut().unwrap();
    let Some(overlay_map) = overlay_val.as_mapping() else {
        return;
    };

    for (section_key, section_val) in overlay_map {
        let Some(overlay_seq) = section_val.as_sequence() else {
            continue;
        };
        let base_entry = base_map
            .entry(section_key.clone())
            .or_insert_with(|| Value::Sequence(Vec::new()));
        let base_seq = base_entry.as_sequence_mut().unwrap();

        for item in overlay_seq {
            let item_name = item
                .as_mapping()
                .and_then(|m| m.get("name"))
                .and_then(|n| n.as_str())
                .expect("Overlay opcode entry missing string `name`");
            if let Some(existing) = base_seq.iter_mut().find(|existing| {
                existing
                    .as_mapping()
                    .and_then(|m| m.get("name"))
                    .and_then(|n| n.as_str())
                    == Some(item_name)
            }) {
                *existing = item.clone();
            } else {
                base_seq.push(item.clone());
            }
        }
    }
}

pub fn append_runtime_protocol_impls(output_str: &mut String, key: &str, opcodes: &[Value]) {
    let domain_expr = domain_expr_for_key(key);

    output_str.push_str(&format!("impl {key} {{\n"));
    output_str.push_str("pub const ALL_NAMED: &'static [(&'static str, u16, u32)] = &[\n");
    for opcode in opcodes {
        let opcode = opcode.as_mapping().unwrap();
        let name = opcode.get("name").unwrap().as_str().unwrap();
        let size = opcode.get("size").unwrap().as_u64().unwrap();
        let opc = opcode.get("opcode").unwrap().as_u64().unwrap();
        output_str.push_str(&format!("(\"{name}\", {opc}, {size}),\n"));
    }
    output_str.push_str("];\n\n");

    output_str.push_str(&format!(
        "pub const fn domain() -> crate::protocol_profile::OpcodeDomain {{\n    {domain_expr}\n}}\n\n"
    ));

    output_str.push_str("pub const fn variant_index(&self) -> Option<usize> {\nmatch self {\n");
    for (idx, opcode) in opcodes.iter().enumerate() {
        let name = opcode
            .as_mapping()
            .unwrap()
            .get("name")
            .unwrap()
            .as_str()
            .unwrap();
        output_str.push_str(&format!("{key}::{name} => Some({idx}),\n"));
    }
    output_str.push_str(&format!("{key}::Unknown(_) => None,\n}}\n}}\n\n"));

    output_str.push_str("pub fn from_variant_index(idx: usize) -> Self {\nmatch idx {\n");
    for (idx, opcode) in opcodes.iter().enumerate() {
        let name = opcode
            .as_mapping()
            .unwrap()
            .get("name")
            .unwrap()
            .as_str()
            .unwrap();
        output_str.push_str(&format!("{idx} => {key}::{name},\n"));
    }
    output_str.push_str("_ => unreachable!(),\n}\n}\n\n");

    output_str.push_str("pub fn from_wire_opcode(raw: u16) -> Self {\n");
    output_str.push_str("    crate::protocol_profile::resolve_wire_index(Self::domain(), raw)\n");
    output_str.push_str("        .map(Self::from_variant_index)\n");
    output_str.push_str("        .unwrap_or(Self::Unknown(raw))\n");
    output_str.push_str("}\n\n");

    output_str.push_str("pub const fn default_opcode(&self) -> u16 {\nmatch self {\n");
    for opcode in opcodes {
        let opcode = opcode.as_mapping().unwrap();
        let name = opcode.get("name").unwrap().as_str().unwrap();
        let opc = opcode.get("opcode").unwrap().as_u64().unwrap();
        output_str.push_str(&format!("{key}::{name} => {opc},\n"));
    }
    output_str.push_str(&format!("{key}::Unknown(opcode) => *opcode,\n}}\n}}\n\n"));

    output_str.push_str("pub const fn default_size(&self) -> u32 {\nmatch self {\n");
    for opcode in opcodes {
        let opcode = opcode.as_mapping().unwrap();
        let name = opcode.get("name").unwrap().as_str().unwrap();
        let size = opcode.get("size").unwrap().as_u64().unwrap();
        output_str.push_str(&format!("{key}::{name} => {size},\n"));
    }
    output_str.push_str(&format!("{key}::Unknown(_) => 0,\n}}\n}}\n\n"));

    // Used for runtime opcode resolution across all IPC packets
    output_str.push_str("/// Returns the active runtime integer opcode.\n");
    output_str.push_str("pub(crate) fn get_opcode(&self) -> u16 {\n");
    output_str.push_str("if let Some(idx) = self.variant_index() {\n");
    output_str
        .push_str("    crate::protocol_profile::resolve_opcode_by_index(Self::domain(), idx)\n");
    output_str.push_str("} else if let Self::Unknown(opcode) = self {\n");
    output_str.push_str("    *opcode\n");
    output_str.push_str("} else {\n");
    output_str.push_str("    unreachable!()\n");
    output_str.push_str("}\n");
    output_str.push_str("}\n\n");
    output_str.push_str("}\n\n");

    output_str.push_str(&format!("impl BinRead for {key} {{\n"));
    output_str.push_str("    type Args<'a> = ();\n");
    output_str.push_str("    fn read_options<R: Read + Seek>(reader: &mut R, endian: Endian, args: Self::Args<'_>) -> BinResult<Self> {\n");
    output_str.push_str("        let raw = u16::read_options(reader, endian, args)?;\n");
    output_str.push_str("        Ok(Self::from_wire_opcode(raw))\n");
    output_str.push_str("    }\n");
    output_str.push_str("}\n\n");

    output_str.push_str(&format!("impl BinWrite for {key} {{\n"));
    output_str.push_str("    type Args<'a> = ();\n");
    output_str.push_str("    fn write_options<W: Write + Seek>(&self, writer: &mut W, endian: Endian, args: Self::Args<'_>) -> BinResult<()> {\n");
    output_str.push_str("        self.get_opcode().write_options(writer, endian, args)\n");
    output_str.push_str("    }\n");
    output_str.push_str("}\n\n");
}

pub fn append_calc_size_impl(output_str: &mut String) {
    output_str.push_str("fn calc_size(&self) -> u32 {\n");
    output_str.push_str("if let Some(idx) = self.variant_index() {\n");
    output_str
        .push_str("    crate::protocol_profile::resolve_size_by_index(Self::domain(), idx)\n");
    output_str.push_str("} else {\n");
    output_str.push_str("    unreachable!()\n");
    output_str.push_str("}\n");
    output_str.push_str("}\n\n");
}
